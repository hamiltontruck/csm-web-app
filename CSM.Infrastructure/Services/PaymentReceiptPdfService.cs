using CSM.Application.Finance.Payments;
using CSM.Application.Finance.Payments.Dtos;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace CSM.Infrastructure.Services;

public class PaymentReceiptPdfService : IPaymentReceiptPdfService
{
    private readonly IPaymentService _paymentService;

    public PaymentReceiptPdfService(IPaymentService paymentService)
    {
        _paymentService = paymentService;
    }

    public async Task<byte[]> GenerateAsync(
        Guid currentUserId,
        Guid paymentId,
        CancellationToken cancellationToken = default)
    {
        var payment = await _paymentService.GetByIdAsync(
            currentUserId,
            paymentId,
            cancellationToken);

        return Generate(payment);
    }

    public byte[] Generate(PaymentResponse payment)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(30);

                page.Header().Column(col =>
                {
                    col.Item().Text("Hamilton Business Group")
                        .FontSize(20).Bold();

                    col.Item().Text("PAYMENT RECEIPT")
                        .FontSize(14)
                        .Bold()
                        .FontColor(Colors.Blue.Darken2);
                });

                page.Content().Column(col =>
                {
                    col.Spacing(8);

                    col.Item().Text($"Receipt No: {payment.PaymentNumber}")
                        .Bold();

                    col.Item().Text($"Date: {payment.PaymentDate:dd MMM yyyy}");
                    col.Item().Text($"Method: {payment.PaymentMethod}");
                    col.Item().Text($"Reference: {payment.ReferenceNumber}");
                    col.Item().Text($"Status: {payment.Status}");

                    col.Item().LineHorizontal(1);

                    col.Item().Row(r =>
                    {
                        r.RelativeItem().Text("Amount").Bold();

                        r.ConstantItem(180)
                            .AlignRight()
                            .Text($"{payment.CurrencyCode} {payment.Amount:N2}")
                            .Bold();
                    });

                    if (!string.IsNullOrWhiteSpace(payment.Notes))
                    {
                        col.Item().PaddingTop(10).Text("Notes").Bold();
                        col.Item().Text(payment.Notes);
                    }

                    col.Item().PaddingTop(30).Text("Authorized Signature");
                    col.Item().LineHorizontal(1);
                });

                page.Footer()
                    .AlignCenter()
                    .Text("Generated by HBG Construction Site Management")
                    .FontSize(9)
                    .FontColor(Colors.Grey.Medium);
            });
        }).GeneratePdf();
    }
}