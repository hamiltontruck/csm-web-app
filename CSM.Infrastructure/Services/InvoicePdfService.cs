using CSM.Application.Finance.Invoices;
using CSM.Application.Finance.Invoices.Dtos;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace CSM.Infrastructure.Services;

public class InvoicePdfService : IInvoicePdfService
{
    private readonly IInvoiceService _invoiceService;

    public InvoicePdfService(IInvoiceService invoiceService)
    {
        _invoiceService = invoiceService;
    }

    public byte[] Generate(InvoiceResponse invoice)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(30);

                page.Header().Column(col =>
                {
                    col.Item().Text("Hamilton Business Group")
                        .FontSize(20).Bold();

                    col.Item().Text("Construction Site Management")
                        .FontSize(10).FontColor(Colors.Grey.Darken2);
                });

                page.Content().Column(col =>
                {
                    col.Spacing(8);

                    col.Item().Text($"Invoice: {invoice.InvoiceNumber}")
                        .FontSize(16).Bold();

                    col.Item().Text($"Status: {invoice.Status}");
                    col.Item().Text($"Invoice Date: {invoice.InvoiceDate:dd MMM yyyy}");
                    col.Item().Text($"Due Date: {invoice.DueDate:dd MMM yyyy}");

                    col.Item().LineHorizontal(1);

                    col.Item().Row(r =>
                    {
                        r.RelativeItem().Text("Total");
                        r.ConstantItem(150)
                            .AlignRight()
                            .Text($"{invoice.CurrencyCode} {invoice.TotalAmount:N2}");
                    });

                    col.Item().Row(r =>
                    {
                        r.RelativeItem().Text("Paid");
                        r.ConstantItem(150)
                            .AlignRight()
                            .Text($"{invoice.CurrencyCode} {invoice.PaidAmount:N2}");
                    });

                    col.Item().Row(r =>
                    {
                        r.RelativeItem().Text("Outstanding").Bold();
                        r.ConstantItem(150)
                            .AlignRight()
                            .Text($"{invoice.CurrencyCode} {invoice.OutstandingAmount:N2}")
                            .Bold();
                    });
                });

                page.Footer()
                    .AlignCenter()
                    .Text("Generated by HBG Construction Site Management")
                    .FontSize(9).FontColor(Colors.Grey.Medium);
            });
        }).GeneratePdf();
    }

    public async Task<byte[]> GenerateAsync(
        Guid currentUserId,
        Guid invoiceId,
        CancellationToken cancellationToken = default)
    {
        var invoice = await _invoiceService.GetByIdAsync(
            currentUserId,
            invoiceId,
            cancellationToken);

        return Generate(invoice);
    }
}